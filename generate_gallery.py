"""Generate videos.html from the actual MP4 files in this repo.

Single source of truth: files on disk. No stale refs, no hand-maintained list.
Run: python3 generate_gallery.py
"""
from pathlib import Path
import html, json

ROOT = Path(__file__).parent
OUT = ROOT / 'videos.html'
BASE = 'https://raw.githubusercontent.com/MYaelMendez/MYaelMendez.github.io/gh-pages/'

files = sorted(p for p in ROOT.rglob('*.mp4') if '.git' not in p.parts)
# exclude generated frame dumps
files = [p for p in files if 'frames' not in p.parts and 'frames' not in p.name]

CATEGORIES = [
    ('✨ AI / Neural', '#00ff9f', lambda n: any(k in n for k in ('fase', 'neuro', 'eee-', 'ai-', 'internetofagents', 'many-agents', 'zeitgeist', 'holomesh', 'capabilities'))),
    ('✝️ Theology', '#ff00ff', lambda n: 'teo' in n or 'teologia' in n),
    ('🤖 Agentic Engineering', '#ffcc00', lambda n: any(k in n for k in ('asimov', 'mujoco', 'studio', 'lc-', 'cod', 'sovereign', 'agentic', 'best-916'))),
    ('💰 Brand / Marketing', '#ff9f00', lambda n: any(k in n for k in ('demo-9x16', 'aertx', 'startabusiness', 'promo', 'launch'))),
    ('📚 Education', '#888888', lambda n: any(k in n for k in ('cri-', 'explain', 'instruct', 'roboflow'))),
]


def cat_of(rel):
    n = rel.lower()
    for name, color, fn in CATEGORIES:
        if fn(n):
            return name, color
    return '📁 Other', '#888888'


groups = {}
for p in files:
    rel = p.relative_to(ROOT).as_posix()
    name, color = cat_of(rel)
    groups.setdefault((name, color), []).append((rel, p.stat().st_size))

parts = []
for (name, color), items in groups.items():
    items.sort(key=lambda x: -x[1])
    total = sum(s for _, s in items)
    rows = ''.join(
        f'<div class="video-item"><span class="play-icon">▶</span>'
        f'<a href="{BASE}{html.escape(rel)}" target="_blank">{html.escape(rel)}</a>'
        f'<span class="size">{s//1024} KB</span></div>'
        for rel, s in items)
    parts.append(
        f'<div class="category"><div class="category-header"><h3><span style="color:{color}">{name}</span></h3>'
        f'<span class="count">{len(items)} videos · {total//1024} KB</span></div>'
        f'<div class="category-body">{rows}</div></div>')

doc = f'''<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>MY Videos — MYaelMendez.github.io</title>
<style>
:root {{ --bg:#0a0a0f; --bg2:#0d0d1a; --fg:#edfff6; --fg2:#8899aa; --accent:#00ff9f; --accent2:#00ccff; --muted:#556677; --border:#1a2a3a; --font:'JetBrains Mono',monospace; }}
* {{ box-sizing:border-box; margin:0; padding:0; }}
body {{ font-family:var(--font); background:var(--bg); color:var(--fg); padding:20px; }}
header {{ text-align:center; padding:20px; border-bottom:1px solid var(--border); }}
header h1 {{ color:var(--accent); font-size:1.8rem; margin-bottom:8px; }}
header p, .count {{ color:var(--muted); font-size:0.9rem; }}
main {{ max-width:1200px; margin:0 auto; padding:20px; }}
.category {{ margin-bottom:24px; }}
.category-header {{ display:flex; justify-content:space-between; align-items:center; border-bottom:1px solid var(--border); padding:8px 0; }}
.category-header h3 {{ font-size:1.1rem; }}
.category-body {{ display:grid; grid-template-columns:repeat(auto-fill,minmax(320px,1fr)); gap:8px; padding-top:12px; }}
.video-item {{ display:flex; align-items:center; gap:10px; background:var(--bg2); border:1px solid var(--border); padding:10px; border-radius:4px; }}
.video-item a {{ color:var(--accent2); text-decoration:none; font-size:0.8rem; overflow:hidden; text-overflow:ellipsis; white-space:nowrap; }}
.video-item:hover {{ border-color:var(--accent); }}
.video-item .size {{ margin-left:auto; color:var(--fg2); font-size:0.7rem; white-space:nowrap; }}
.play-icon {{ color:var(--accent); }}
footer {{ text-align:center; color:var(--muted); padding:30px; font-size:0.8rem; }}
</style>
</head>
<body>
<header>
<h1>_æ MY Videos</h1>
<p>Generated from files on disk — single source of truth.</p>
<p class="count">{len(files)} videos · {sum(p.stat().st_size for p in files)//1024} KB</p>
</header>
<main>
{"".join(parts)}
</main>
<footer>
<p>HUMAN://ROOT · receipts on every action · &gt;_æ:</p>
<p>Generated by <code>generate_gallery.py</code> · {len(files)} live MP4 files</p>
</footer>
</body>
</html>
'''
OUT.write_text(doc, encoding='utf-8')
print(json.dumps({'success': True, 'files': len(files), 'categories': len(groups), 'output': str(OUT),
                  'sha256': __import__('hashlib').sha256(OUT.read_bytes()).hexdigest()}))
